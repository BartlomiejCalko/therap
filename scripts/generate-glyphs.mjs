// Turns the line drawings in assets/icons/*.svg into data for <Glyph />.
// Run after adding or changing an icon: node scripts/generate-glyphs.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'assets/icons';
const OUT = 'src/components/glyphs.generated.ts';

// File prefix → name used in code.
const NAMES = {
  '01': 'pen',
  '02': 'inkDrop',
  '03': 'hourglass',
  '04': 'sessionPause',
  '05': 'sessionClarity',
  '06': 'sessionSpace',
  '07': 'sessionRelease',
  '08': 'sunrise',
  '09': 'feather',
  '10': 'rise',
  '11': 'unload',
  '12': 'page',
  '13': 'letter',
  '14': 'moon',
  '15': 'spark',
  '16': 'ginkgo',
  '17': 'cloud',
  '18': 'key',
  '19': 'arch',
  '20': 'flame',
  '21': 'done',
  '22': 'breath',
};

const NUMERIC = new Set(['cx', 'cy', 'r', 'x1', 'y1', 'x2', 'y2', 'stroke-width']);
const camel = (s) => s.replace(/-([a-z])/g, (_, ch) => ch.toUpperCase());

const glyphs = {};
for (const file of readdirSync(SRC).filter((f) => f.endsWith('.svg')).sort()) {
  const name = NAMES[file.slice(0, 2)];
  if (!name) throw new Error(`No name for ${file}; add it to NAMES.`);
  const svg = readFileSync(join(SRC, file), 'utf8');
  const shapes = [];
  for (const [, tag, attrs] of svg.matchAll(/<(path|line|circle)\s([^>]*?)\/>/g)) {
    const props = {};
    for (const [, key, value] of attrs.matchAll(/([a-z0-9-]+)="([^"]*)"/g)) {
      // Black is the drawing colour; it becomes whatever colour the glyph is given.
      if ((key === 'fill' || key === 'stroke') && value === '#000') props[key] = 'ink';
      else props[camel(key)] = NUMERIC.has(key) ? Number(value) : value;
    }
    shapes.push([tag, props]);
  }
  glyphs[name] = shapes;
}

const body = Object.entries(glyphs)
  .map(([name, shapes]) => `  ${name}: ${JSON.stringify(shapes)},`)
  .join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/generate-glyphs.mjs from assets/icons. Do not edit by hand.
// Each shape is [tag, props] on a 64×64 grid; 'ink' stands for the glyph's colour.

export type GlyphShape = ['path' | 'line' | 'circle', Record<string, string | number>];

export type GlyphName =
${Object.keys(glyphs).map((n) => `  | '${n}'`).join('\n')};

export const GLYPHS: Record<GlyphName, GlyphShape[]> = {
${body}
};
`,
);
console.log(`Wrote ${Object.keys(glyphs).length} glyphs to ${OUT}`);
